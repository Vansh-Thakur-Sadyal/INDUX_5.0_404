"""The farm report as a PDF: a document, not a JSON dump with a serif font.

Built with reportlab's platypus flowables so the content paginates itself, and with
its own chart primitives rather than matplotlib - one fewer heavy dependency in the
image, and the charts come out as vectors, so they stay sharp when printed.

Two rules carried over from the rest of the system:

* Provenance travels with the number. A simulated reading is marked SIMULATED on the
  page, an estimate is marked estimated, and a farmer's own figure is marked as theirs.
  A report that hides where a number came from is worse than no report.
* Nothing is invented to fill a section. An empty section says it is empty.
"""
from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Sequence

from reportlab.graphics.charts.barcharts import VerticalBarChart
from reportlab.graphics.charts.legends import Legend
from reportlab.graphics.charts.linecharts import HorizontalLineChart
from reportlab.graphics.charts.piecharts import Pie
from reportlab.graphics.shapes import Drawing, Line, Rect, String
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (KeepTogether, PageBreak, Paragraph, SimpleDocTemplate,
                                Spacer, Table, TableStyle)

# The dashboard's palette, so the report looks like the product it came from.
GREEN = colors.HexColor("#1f9d4d")
GREEN_DARK = colors.HexColor("#15803d")
GREEN_SOFT = colors.HexColor("#e9f6ec")
INK = colors.HexColor("#17251d")
MUTED = colors.HexColor("#6c7f71")
LINE = colors.HexColor("#d9e6dc")
AMBER = colors.HexColor("#d9930c")
RED = colors.HexColor("#c6513f")
BLUE = colors.HexColor("#2f80d6")

PAGE = A4
MARGIN = 16 * mm


def _styles() -> Dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=base["Title"], fontSize=26, leading=30,
                                textColor=INK, spaceAfter=2),
        "subtitle": ParagraphStyle("st", parent=base["Normal"], fontSize=11, leading=15,
                                   textColor=MUTED),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontSize=14, leading=18,
                             textColor=GREEN_DARK, spaceBefore=14, spaceAfter=6),
        "h3": ParagraphStyle("h3", parent=base["Heading3"], fontSize=10.5, leading=14,
                             textColor=INK, spaceBefore=8, spaceAfter=4),
        "body": ParagraphStyle("b", parent=base["Normal"], fontSize=9.5, leading=13.5,
                               textColor=INK),
        "muted": ParagraphStyle("m", parent=base["Normal"], fontSize=8.5, leading=12,
                                textColor=MUTED),
        "cell": ParagraphStyle("c", parent=base["Normal"], fontSize=8.5, leading=11.5,
                               textColor=INK),
        "centre": ParagraphStyle("ce", parent=base["Normal"], fontSize=9, leading=12,
                                 alignment=TA_CENTER, textColor=MUTED),
    }


def _fmt(value: Any, dash: str = "-") -> str:
    if value is None or value == "":
        return dash
    if isinstance(value, float):
        return ("%.2f" % value).rstrip("0").rstrip(".")
    return str(value)


def _when(value: Any) -> str:
    text = str(value or "")
    return text.replace("T", " ")[:16] if text else "-"


# --------------------------------------------------------------- furniture
def _page_furniture(canvas, doc) -> None:
    """Header rule and footer on every page."""
    canvas.saveState()
    width, height = PAGE

    canvas.setFillColor(GREEN)
    canvas.rect(0, height - 6 * mm, width, 6 * mm, stroke=0, fill=1)

    canvas.setFont("Helvetica-Bold", 8.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(MARGIN, height - 12 * mm, "SAARTHI 2.0")
    canvas.drawRightString(width - MARGIN, height - 12 * mm,
                           doc.report_title.upper() if hasattr(doc, "report_title") else "")

    canvas.setStrokeColor(LINE)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, height - 14 * mm, width - MARGIN, height - 14 * mm)

    canvas.setFont("Helvetica", 7.5)
    canvas.drawString(MARGIN, 10 * mm,
                      "Generated by Saarthi 2.0. Figures carry the service they came from.")
    canvas.drawRightString(width - MARGIN, 10 * mm, "Page %d" % canvas.getPageNumber())
    canvas.restoreState()


def _tiles(items: Sequence[Sequence[str]], width: float) -> Drawing:
    """The dashboard's metric tiles, drawn rather than tabulated."""
    count = max(1, len(items))
    gap = 5
    tile_w = (width - gap * (count - 1)) / count
    height = 46
    d = Drawing(width, height)
    for i, (label, value, sub) in enumerate(items):
        x = i * (tile_w + gap)
        d.add(Rect(x, 0, tile_w, height, rx=5, ry=5,
                   fillColor=GREEN_SOFT, strokeColor=LINE, strokeWidth=0.6))
        d.add(String(x + 9, height - 15, str(label)[:26], fontName="Helvetica",
                     fontSize=7.5, fillColor=MUTED))
        d.add(String(x + 9, height - 32, str(value)[:18], fontName="Helvetica-Bold",
                     fontSize=15, fillColor=GREEN_DARK))
        if sub:
            d.add(String(x + 9, 7, str(sub)[:34], fontName="Helvetica", fontSize=7,
                         fillColor=MUTED))
    return d


def _bar_chart(pairs: Sequence[Sequence[Any]], width: float, height: float = 150,
               colour=GREEN, label: str = "") -> Drawing:
    d = Drawing(width, height)
    chart = VerticalBarChart()
    chart.x, chart.y = 34, 30
    chart.width, chart.height = width - 50, height - 50
    chart.data = [[float(v or 0) for _, v in pairs]]
    chart.categoryAxis.categoryNames = [str(k)[:14] for k, _ in pairs]
    chart.categoryAxis.labels.fontSize = 7
    chart.categoryAxis.labels.angle = 20 if max((len(str(k)) for k, _ in pairs), default=0) > 7 else 0
    chart.categoryAxis.labels.dy = -6
    chart.valueAxis.valueMin = 0
    top = max([float(v or 0) for _, v in pairs] + [1])
    chart.valueAxis.valueMax = top * 1.15
    chart.valueAxis.labels.fontSize = 7
    chart.bars[0].fillColor = colour
    chart.bars.strokeWidth = 0
    chart.barWidth = 9
    chart.groupSpacing = 8
    d.add(chart)
    if label:
        d.add(String(0, height - 10, label, fontName="Helvetica-Bold", fontSize=8.5,
                     fillColor=INK))
    return d


def _line_chart(series: Sequence[float], labels: Sequence[str], width: float,
                height: float = 140, label: str = "") -> Drawing:
    d = Drawing(width, height)
    chart = HorizontalLineChart()
    chart.x, chart.y = 34, 26
    chart.width, chart.height = width - 50, height - 46
    chart.data = [list(series)]
    chart.categoryAxis.categoryNames = list(labels)
    chart.categoryAxis.labels.fontSize = 6.5
    chart.categoryAxis.labels.angle = 30
    chart.categoryAxis.labels.dy = -8
    low, high = (min(series), max(series)) if series else (0, 1)
    pad = max(1.0, (high - low) * 0.2)
    chart.valueAxis.valueMin = max(0, low - pad)
    chart.valueAxis.valueMax = high + pad
    chart.valueAxis.labels.fontSize = 7
    chart.lines[0].strokeColor = BLUE
    chart.lines[0].strokeWidth = 1.6
    d.add(chart)
    if label:
        d.add(String(0, height - 10, label, fontName="Helvetica-Bold", fontSize=8.5,
                     fillColor=INK))
    return d


def _donut(percent: float, caption: str, width: float = 150) -> Drawing:
    """A single proportion, for things like model coverage."""
    d = Drawing(width, 120)
    pie = Pie()
    pie.x, pie.y = (width - 80) / 2, 24
    pie.width = pie.height = 80
    value = max(0.0, min(100.0, float(percent)))
    pie.data = [value, 100 - value]
    pie.slices[0].fillColor = GREEN
    pie.slices[1].fillColor = colors.HexColor("#e7efe6")
    pie.slices.strokeWidth = 0
    pie.innerRadiusFraction = 0.58
    d.add(pie)
    d.add(String(width / 2, 60, "%d%%" % round(value), fontName="Helvetica-Bold",
                 fontSize=15, fillColor=INK, textAnchor="middle"))
    d.add(String(width / 2, 8, caption[:34], fontName="Helvetica", fontSize=7.5,
                 fillColor=MUTED, textAnchor="middle"))
    return d


def _range_rows(parameters: Sequence[Dict[str, Any]], width: float) -> Drawing:
    """One row per parameter: its typical band, and where this reading sits in it.

    The right way to show four quantities in four different units. A shared axis would
    be a lie; a band each is the comparison that actually means something - is this
    number where it should be?
    """
    row_h = 26
    d = Drawing(width, row_h * len(parameters) + 6)
    label_w = width * 0.30
    track_x = label_w + 6
    track_w = width - track_x - 56

    for i, p in enumerate(parameters):
        y = d.height - (i + 1) * row_h + 8
        low, high = (list(p.get("typical_range") or [0, 1]) + [0, 1])[:2]
        low, high = float(low), float(high)
        value = float(p.get("value") or 0)

        # The drawn span covers the typical range plus a margin, so a value outside it
        # is still visible rather than clamped onto the edge.
        span_lo = min(low, value) - (high - low) * 0.25
        span_hi = max(high, value) + (high - low) * 0.25
        span = max(span_hi - span_lo, 1e-6)

        d.add(String(0, y + 1, str(p.get("label", ""))[:30], fontName="Helvetica",
                     fontSize=8, fillColor=INK))
        d.add(Rect(track_x, y - 1, track_w, 7, rx=3, ry=3,
                   fillColor=colors.HexColor("#eef3ed"), strokeColor=None))

        band_x = track_x + (low - span_lo) / span * track_w
        band_w = max(2.0, (high - low) / span * track_w)
        d.add(Rect(band_x, y - 1, band_w, 7, rx=3, ry=3,
                   fillColor=GREEN_SOFT, strokeColor=GREEN, strokeWidth=0.6))

        mark_x = track_x + (value - span_lo) / span * track_w
        inside = low <= value <= high
        d.add(Line(mark_x, y - 4, mark_x, y + 9,
                   strokeColor=GREEN_DARK if inside else AMBER, strokeWidth=2))
        d.add(String(track_x + track_w + 6, y + 1,
                     "%s %s" % (_fmt(value), p.get("unit", "")),
                     fontName="Helvetica-Bold", fontSize=8,
                     fillColor=GREEN_DARK if inside else AMBER))
    return d


def _table(rows: List[List[Any]], widths: Sequence[float], styles,
           align_right: Sequence[int] = ()) -> Table:
    body = [[Paragraph("<b>%s</b>" % _fmt(c), styles["cell"]) for c in rows[0]]]
    for row in rows[1:]:
        body.append([Paragraph(_fmt(c), styles["cell"]) for c in row])
    table = Table(body, colWidths=list(widths), repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), GREEN_SOFT),
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, GREEN),
        ("LINEBELOW", (0, 1), (-1, -1), 0.3, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
    ]
    for column in align_right:
        style.append(("ALIGN", (column, 1), (column, -1), "RIGHT"))
    table.setStyle(TableStyle(style))
    return table


def _note(text: str, styles, tone: str = "muted"):
    colour = {"muted": LINE, "warn": AMBER, "bad": RED}.get(tone, LINE)
    cell = Paragraph(text, styles["muted"])
    box = Table([[cell]], colWidths=[PAGE[0] - 2 * MARGIN])
    box.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.6, colour),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fbfdfa")),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return box


# ------------------------------------------------------------------ report
def build(report_id: str, data: Dict[str, Any], *, farm: Optional[Dict[str, Any]] = None,
          title: str = "") -> bytes:
    """Render one report to PDF bytes."""
    styles = _styles()
    buffer = io.BytesIO()
    heading = title or report_id.replace("-", " ").title()

    doc = SimpleDocTemplate(
        buffer, pagesize=PAGE,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=MARGIN + 6 * mm, bottomMargin=MARGIN,
        title="Saarthi 2.0 - %s" % heading, author="Saarthi 2.0")
    doc.report_title = heading
    width = PAGE[0] - 2 * MARGIN

    story: List[Any] = []
    story.append(Paragraph("Saarthi 2.0", styles["title"]))
    story.append(Paragraph(heading, styles["h2"]))

    who = farm or {}
    # The field this report is about, when it is about one. A report for the
    # whole farm says nothing here rather than naming a plot it did not read.
    where = ""
    if who.get("field_name"):
        where = "Field " + str(who["field_name"])
        if who.get("field_crop"):
            where += " (%s)" % who["field_crop"]
    line = " &middot; ".join(x for x in [
        who.get("farmer_name") or who.get("name"),
        where,
        ("Village " + who["village"]) if who.get("village") else "",
        ("District " + who["district"]) if who.get("district") else "",
        ("%s acres" % _fmt(who.get("area_acres") or who.get("land_acres")))
        if (who.get("area_acres") or who.get("land_acres")) else "",
    ] if x)
    story.append(Paragraph(line or "Farm record", styles["subtitle"]))
    story.append(Paragraph(
        "Generated %s UTC" % datetime.now(timezone.utc).strftime("%d %b %Y, %H:%M"),
        styles["muted"]))
    story.append(Spacer(1, 10))

    builder = {
        "soil": _soil_section,
        "advisory": _advisory_section,
        "calls": _calls_section,
        "sensor-history": _sensor_history_section,
    }.get(report_id)

    if builder is None:
        story.append(Paragraph("No renderer for this report.", styles["body"]))
    else:
        story.extend(builder(data, styles, width))

    doc.build(story, onFirstPage=_page_furniture, onLaterPages=_page_furniture)
    return buffer.getvalue()


# ----------------------------------------------------------------- sections
def _provenance_line(reading: Dict[str, Any]) -> str:
    mode = str(reading.get("mode") or "")
    provenance = str(reading.get("provenance") or "")
    if provenance == "farmer_reported":
        return ("These figures were entered by the farmer, not measured by a device. "
                "They are treated as the farmer's own statement.")
    if mode == "simulation":
        return ("SIMULATED DATA. These readings were generated for demonstration and "
                "did not come from a sensor in a field. Do not act on them.")
    return "Measured by the farm's own 7-in-1 sensor."


def _soil_section(data: Dict[str, Any], styles, width: float) -> List[Any]:
    reading = data.get("reading") or {}
    validation = data.get("validation") or {}
    parameters = data.get("parameters") or []
    index = data.get("index") or {}
    out: List[Any] = []

    tone = "warn" if str(reading.get("mode")) == "simulation" else "muted"
    out.append(_note("<b>Where these numbers came from.</b> " + _provenance_line(reading),
                     styles, tone))
    out.append(Spacer(1, 10))

    out.append(_tiles([
        ("Soil index", _fmt(index.get("index", "-")), str(index.get("label", ""))),
        ("Validation", str(validation.get("status", "-")).title(),
         "%s%% usable" % round(100 * float(validation.get("completeness") or 0))),
        ("Device", str(reading.get("device_id", "-"))[:16], str(reading.get("mode", ""))),
        ("Recorded", _when(reading.get("recorded_at")), ""),
    ], width))
    out.append(Spacer(1, 12))

    # Nutrients share a unit, so a bar chart compares them honestly. pH, temperature,
    # moisture and EC do not: putting 195 mg/kg of potassium beside a pH of 7.2 on one
    # axis makes the pH invisible and implies a comparison that does not exist.
    nutrients = [(p.get("label", ""), p.get("value")) for p in parameters
                 if p.get("unit") == "mg/kg" and isinstance(p.get("value"), (int, float))]
    if nutrients:
        out.append(Paragraph("Nutrients (mg/kg)", styles["h2"]))
        out.append(_bar_chart(nutrients, width, 150, GREEN))
        out.append(Spacer(1, 6))

    others = [p for p in parameters
              if p.get("unit") != "mg/kg" and isinstance(p.get("value"), (int, float))
              and p.get("typical_range")]
    if others:
        out.append(Paragraph("Everything else, against its typical range", styles["h2"]))
        out.append(_range_rows(others, width))
        out.append(Spacer(1, 8))

    if parameters:
        rows = [["Parameter", "Value", "Unit", "Band", "Typical range"]]
        for p in parameters:
            low_high = p.get("typical_range") or []
            rows.append([p.get("label"), _fmt(p.get("value")), p.get("unit"),
                         p.get("band"),
                         "%s to %s" % (_fmt(low_high[0]), _fmt(low_high[1]))
                         if len(low_high) == 2 else "-"])
        out.append(_table(rows, [width * 0.26, width * 0.12, width * 0.11,
                                 width * 0.18, width * 0.33], styles, align_right=(1,)))

    warnings = validation.get("warnings") or []
    errors = validation.get("errors") or []
    if warnings or errors:
        out.append(Paragraph("Validation notes", styles["h2"]))
        for item in list(errors) + list(warnings):
            out.append(Paragraph("&bull; " + str(item), styles["body"]))
    return out


def _advisory_section(data: Dict[str, Any], styles, width: float) -> List[Any]:
    advisories = data.get("advisories") or []
    out: List[Any] = []
    if not advisories:
        out.append(Paragraph("No advisory has been generated yet.", styles["body"]))
        return out

    intents: Dict[str, int] = {}
    for item in advisories:
        key = str(item.get("intent") or "general")
        intents[key] = intents.get(key, 0) + 1
    ranked = sorted(intents.items(), key=lambda kv: -kv[1])

    out.append(_tiles([
        ("Advisories", str(len(advisories)), "most recent first"),
        ("Topics", str(len(intents)), "distinct intents"),
        ("Most asked", ranked[0][0].replace("_", " ") if ranked else "-",
         "%d of %d" % (ranked[0][1], len(advisories)) if ranked else ""),
    ], width))
    out.append(Spacer(1, 12))

    out.append(Paragraph("What the farmer asks about", styles["h2"]))
    out.append(_bar_chart([(k.replace("_", " "), v) for k, v in ranked[:8]],
                          width, 160, GREEN))
    out.append(Spacer(1, 8))

    out.append(Paragraph("Advisory history", styles["h2"]))
    rows = [["When", "Intent", "Question", "Agents"]]
    for item in advisories[:40]:
        rows.append([_when(item.get("created_at")),
                     str(item.get("intent", "")).replace("_", " "),
                     str(item.get("question", ""))[:110],
                     len(item.get("agents_invoked") or []) or ""])
    out.append(_table(rows, [width * 0.15, width * 0.15, width * 0.57, width * 0.13],
                      styles, align_right=(3,)))
    return out


def _calls_section(data: Dict[str, Any], styles, width: float) -> List[Any]:
    calls = data.get("calls") or []
    out: List[Any] = []
    if not calls:
        out.append(Paragraph("No calls recorded yet.", styles["body"]))
        return out

    statuses: Dict[str, int] = {}
    turns_total = 0
    for call in calls:
        statuses[str(call.get("status") or "?")] = statuses.get(str(call.get("status") or "?"), 0) + 1
        turns_total += len((call.get("detail") or {}).get("turns") or [])
    finished = statuses.get("completed", 0)

    out.append(_tiles([
        ("Calls", str(len(calls)), "most recent first"),
        ("Spoken turns", str(turns_total), "across all calls"),
        ("Finished", str(finished), "reached a normal end"),
    ], width))
    out.append(Spacer(1, 12))

    if statuses:
        out.append(Paragraph("How calls ended", styles["h2"]))
        out.append(_bar_chart(sorted(statuses.items(), key=lambda kv: -kv[1]),
                              width, 150, BLUE))
        out.append(Spacer(1, 6))
        out.append(_donut(100.0 * finished / max(1, len(calls)),
                          "of calls finished normally", width))
        out.append(Spacer(1, 8))

    out.append(Paragraph("Call log", styles["h2"]))
    rows = [["When", "Phone", "Direction", "Status", "Turns", "Last thing said"]]
    for call in calls[:40]:
        detail = call.get("detail") or {}
        turns = detail.get("turns") or []
        last = turns[-1].get("question", "") if turns else ""
        rows.append([_when(call.get("created_at")), call.get("phone"),
                     call.get("direction"), call.get("status"), len(turns), last[:70]])
    out.append(_table(rows, [width * 0.14, width * 0.17, width * 0.11, width * 0.14,
                             width * 0.08, width * 0.36], styles, align_right=(4,)))
    return out


def _sensor_history_section(data: Dict[str, Any], styles, width: float) -> List[Any]:
    readings = data.get("readings") or []
    out: List[Any] = []
    if not readings:
        out.append(Paragraph("No sensor readings stored yet.", styles["body"]))
        return out

    ordered = list(reversed(readings))
    simulated = sum(1 for r in readings if str(r.get("mode")) == "simulation")
    out.append(_note(
        "<b>%d of %d readings are SIMULATED.</b> Simulated records are generated for "
        "demonstration and did not come from a device in a field." % (simulated, len(readings)),
        styles, "warn" if simulated else "muted"))
    out.append(Spacer(1, 10))

    out.append(_tiles([
        ("Readings", str(len(readings)), "stored"),
        ("Simulated", str(simulated), "labelled as such"),
        ("Real", str(len(readings) - simulated), "from a device"),
        ("Latest", _when(ordered[-1].get("recorded_at")), ""),
    ], width))
    out.append(Spacer(1, 12))

    # All seven the probe reports, not the three that happened to be charted:
    # a farmer looking at a nitrogen trend should not have to read it out of the
    # table underneath. A parameter with fewer than two readings is skipped,
    # because one point is not a trend and an empty axis says nothing.
    for field, label in (("moisture_pct", "Soil moisture (%)"),
                         ("temperature_c", "Soil temperature (C)"),
                         ("ph", "pH"),
                         ("ec_ds_m", "EC (dS/m)"),
                         ("nitrogen_mg_kg", "Nitrogen (mg/kg)"),
                         ("phosphorus_mg_kg", "Phosphorus (mg/kg)"),
                         ("potassium_mg_kg", "Potassium (mg/kg)")):
        series = [float(r[field]) for r in ordered
                  if isinstance(r.get(field), (int, float))]
        if len(series) < 2:
            continue
        labels = [_when(r.get("recorded_at"))[5:16] for r in ordered
                  if isinstance(r.get(field), (int, float))]
        step = max(1, len(labels) // 10)
        labels = [l if i % step == 0 else "" for i, l in enumerate(labels)]
        out.append(KeepTogether([Paragraph(label, styles["h3"]),
                                 _line_chart(series, labels, width, 140)]))
        out.append(Spacer(1, 6))

    out.append(Paragraph("Readings", styles["h2"]))
    rows = [["Recorded", "Mode", "Moisture %", "Temp C", "pH", "EC dS/m", "N", "P", "K"]]
    for r in readings[:45]:
        rows.append([_when(r.get("recorded_at")), r.get("mode"),
                     _fmt(r.get("moisture_pct")), _fmt(r.get("temperature_c")),
                     _fmt(r.get("ph")), _fmt(r.get("ec_ds_m")),
                     _fmt(r.get("nitrogen_mg_kg")), _fmt(r.get("phosphorus_mg_kg")),
                     _fmt(r.get("potassium_mg_kg"))])
    out.append(_table(rows, [width * 0.17, width * 0.12] + [width * 0.1017] * 7,
                      styles, align_right=(2, 3, 4, 5, 6, 7, 8)))
    return out
